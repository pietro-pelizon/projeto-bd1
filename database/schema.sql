DROP TABLE IF EXISTS resposta CASCADE;
DROP TABLE IF EXISTS atribuicao CASCADE;
DROP TABLE IF EXISTS avaliacao_questao CASCADE;
DROP TABLE IF EXISTS alternativa CASCADE;
DROP TABLE IF EXISTS questao_discursiva CASCADE;
DROP TABLE IF EXISTS questao_multipla_escolha CASCADE;
DROP TABLE IF EXISTS avaliacao CASCADE;
DROP TABLE IF EXISTS questao CASCADE;
DROP TABLE IF EXISTS usuario CASCADE;
DROP DOMAIN IF EXISTS opcoes_t CASCADE;
DROP DOMAIN IF EXISTS nota_t CASCADE;

-- Domínios
CREATE DOMAIN opcoes_t AS VARCHAR(1)
    CONSTRAINT ck_letra CHECK (VALUE IN ('A', 'B', 'C', 'D', 'E', 'F', 'G'));

CREATE DOMAIN nota_t AS NUMERIC(4, 2)
    CONSTRAINT ck_nota_intervalo CHECK (VALUE >= 0 AND VALUE <= 10);

-- Tabelas independentes
CREATE TABLE usuario (
    id_usuario INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(320) NOT NULL UNIQUE,
    nome VARCHAR(100) NOT NULL,
    senha VARCHAR(64) NOT NULL,
    tipo VARCHAR(10) NOT NULL
);

CREATE TABLE questao (
    id_questao INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    enunciado TEXT NOT NULL
);

CREATE TABLE avaliacao (
    id_avaliacao INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo TEXT NOT NULL,
    data DATE NOT NULL,
    descricao TEXT NOT NULL,
    hora_inicio TIME NOT NULL,
    hora_fim TIME NOT NULL,
    CONSTRAINT ck_avaliacao_horario CHECK (hora_fim > hora_inicio)
);

-- Tabelas com somente 1 atributo como FK
CREATE TABLE questao_multipla_escolha (
    id_questao INT PRIMARY KEY,
    CONSTRAINT fk_questao_multipla_escolha FOREIGN KEY (id_questao) REFERENCES questao(id_questao) ON DELETE CASCADE
);

CREATE TABLE questao_discursiva (
    id_questao INT PRIMARY KEY,
    CONSTRAINT fk_questao_discursiva FOREIGN KEY (id_questao) REFERENCES questao(id_questao) ON DELETE CASCADE
);

-- Tabelas com 2 atributos na FK
CREATE TABLE alternativa (
    id_questao INT NOT NULL,
    letra opcoes_t NOT NULL,
    correta BOOLEAN NOT NULL DEFAULT FALSE,
    texto TEXT NOT NULL,
    CONSTRAINT pk_alternativa PRIMARY KEY (id_questao, letra),
    CONSTRAINT fk_alternativa_questao FOREIGN KEY (id_questao)
        REFERENCES questao_multipla_escolha(id_questao) ON DELETE CASCADE
);

CREATE TABLE avaliacao_questao (
    id_avaliacao INT NOT NULL,
    id_questao INT NOT NULL,
    valor nota_t NOT NULL,
    CONSTRAINT pk_avaliacao_questao PRIMARY KEY (id_avaliacao, id_questao),
    CONSTRAINT fk_aq_avaliacao FOREIGN KEY (id_avaliacao) REFERENCES avaliacao(id_avaliacao) ON DELETE CASCADE, -- Se deleta Avaliacao, faz sentido Questao na avaliaco sumir também
    CONSTRAINT fk_aq_questao FOREIGN KEY (id_questao) REFERENCES questao(id_questao) ON DELETE RESTRICT
);

CREATE TABLE atribuicao (
    id_usuario INT NOT NULL,
    id_avaliacao INT NOT NULL,
    status TEXT NOT NULL DEFAULT 'NAO_INICIADO',
    CONSTRAINT pk_atribuicao PRIMARY KEY (id_usuario, id_avaliacao),
    CONSTRAINT fk_atribuicao_usuario FOREIGN KEY (id_usuario) REFERENCES usuario(id_usuario) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_atribuicao_avaliacao FOREIGN KEY (id_avaliacao) REFERENCES avaliacao(id_avaliacao) ON DELETE CASCADE,
    CONSTRAINT ck_status CHECK (status IN ('CONCLUIDO', 'EM_ANDAMENTO', 'NAO_INICIADO'))
);

CREATE TABLE resposta (
    id_usuario INT NOT NULL,
    id_avaliacao INT NOT NULL,
    id_questao INT NOT NULL,
    texto_resposta TEXT,
    letra_marcada opcoes_t,
    nota nota_t,
    CONSTRAINT pk_resposta PRIMARY KEY (id_usuario, id_avaliacao, id_questao),
    CONSTRAINT fk_resposta_atribuicao FOREIGN KEY (id_usuario, id_avaliacao)
        REFERENCES atribuicao(id_usuario, id_avaliacao) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_resposta_questao FOREIGN KEY (id_questao) REFERENCES questao(id_questao) ON DELETE RESTRICT
);